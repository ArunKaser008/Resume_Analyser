import { useCallback, useEffect, useState } from 'react'
import { ApiError } from '../../api/client'
import { downloadResume, downloadResumeDocx, getResumePreview, updateResumeTemplate } from '../../api/resumes'
import type { Resume, ResumeTemplate } from '../../api/types'

export default function ResumePreviewPage({ resume, onResumeChanged, onBack }: {
  resume: Resume
  onResumeChanged: (resume: Resume) => void
  onBack: () => void
}) {
  const [html, setHtml] = useState('')
  const [loading, setLoading] = useState(true)
  const [downloading, setDownloading] = useState(false)
  const [error, setError] = useState('')
  const [notice, setNotice] = useState('')
  const [template, setTemplate] = useState<ResumeTemplate>(resume.template_name)

  const refresh = useCallback(async () => {
    setLoading(true)
    try {
      setHtml(await getResumePreview(resume.id))
    } catch (cause) {
      setError(cause instanceof ApiError ? cause.message : 'Unable to load the resume preview.')
    } finally {
      setLoading(false)
    }
  }, [resume.id])
  useEffect(() => {
    let active = true
    void getResumePreview(resume.id)
      .then((result) => { if (active) setHtml(result) })
      .catch((cause: unknown) => { if (active) setError(cause instanceof ApiError ? cause.message : 'Unable to load the resume preview.') })
      .finally(() => { if (active) setLoading(false) })
    return () => { active = false }
  }, [resume.id])

  const saveTemplate = async (value: ResumeTemplate) => {
    setTemplate(value)
    setError('')
    try {
      await updateResumeTemplate(resume.id, value)
      onResumeChanged({ ...resume, template_name: value })
      setNotice('Template updated.')
      await refresh()
    } catch (cause) {
      setTemplate(resume.template_name)
      setError(cause instanceof Error ? cause.message : 'Unable to update the template.')
    }
  }
  const download = async (format: 'pdf' | 'docx') => {
    setDownloading(true)
    setError('')
    try {
      const file = format === 'pdf'
        ? await downloadResume(resume.id)
        : await downloadResumeDocx(resume.id)
      const url = URL.createObjectURL(file)
      const link = document.createElement('a')
      link.href = url
      link.download = `${resume.title.replace(/[^\w.-]+/g, '-')}.${format}`
      document.body.append(link)
      link.click()
      link.remove()
      URL.revokeObjectURL(url)
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'Unable to download the PDF.')
    } finally {
      setDownloading(false)
    }
  }

  return <div className="feature-page preview-page">
    <div className="page-heading"><div><div className="eyebrow">RESUME PREVIEW</div><h1>{resume.title}</h1><p>Preview is generated by the backend using the selected template and resume content.</p></div><div className="heading-actions"><button className="button button-secondary" onClick={onBack}>← Back to resume</button><button className="button button-secondary" disabled={downloading} onClick={() => void download('docx')}>{downloading ? 'Preparing…' : '↓ Download DOCX'}</button><button className="button button-primary" disabled={downloading} onClick={() => void download('pdf')}>{downloading ? 'Preparing…' : '↓ Download PDF'}</button></div></div>
    <section className="panel preview-toolbar"><label>Template<select value={template} onChange={(event) => void saveTemplate(event.target.value as ResumeTemplate)}><option value="modern">Modern</option><option value="professional">Professional</option><option value="minimal">Minimal</option></select></label><button className="button button-secondary" onClick={() => void refresh()}>Refresh preview</button></section>
    {error && <div className="notice notice-error" role="alert">{error}</div>}{notice && <div className="notice notice-success" role="status">{notice}</div>}
    <div className="preview-frame-wrap">{loading ? <div className="panel empty-state"><span className="spinner" /><p>Rendering your resume…</p></div> : html ? <iframe className="preview-frame" title={`${resume.title} preview`} sandbox="" srcDoc={html} /> : <div className="panel empty-state"><h2>No preview available</h2><p>The preview endpoint returned an empty document.</p></div>}</div>
  </div>
}
